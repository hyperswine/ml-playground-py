import argparse
import gzip
import hashlib
import json
import re
import shutil
from collections import Counter
from pathlib import Path
from urllib.parse import urlsplit

import numpy as np
import torch
from tokenizers import Tokenizer

from qos_ai_data import digest, file_hash, read_rows
from qos_ai_scale import write_json


SOURCES = {
  'english': {'repo': 'HuggingFaceFW/fineweb-edu',
              'revision': '87f09149ef4734204d70ed1d046ddc9ca3f2b8f9',
              'files': ['sample/10BT/000_00000.parquet', 'sample/10BT/001_00000.parquet'],
              'license': 'ODC-BY; underlying web-content rights vary', 'weight': .8},
  'python': {'repo': 'codeparrot/codeparrot-clean',
             'revision': '35a59fb025bc0a102f7d96eac09d145b896d487b',
             'files': [f'file-{i:012d}.json.gz' for i in range(1, 7)],
             'license': 'per-file permissive allowlist', 'weight': .2},
}
PERMISSIVE = {'mit', 'apache-2.0', 'bsd-2-clause', 'bsd-3-clause', 'isc', 'cc0-1.0', 'unlicense'}


class FrozenTokenizer:
  def __init__(self, path):
    self.backend = Tokenizer.from_file(str(Path(path) / 'tokenizer.json'))

  def __len__(self):
    return self.backend.get_vocab_size()

  def encode(self, text, add_special_tokens=False):
    return self.backend.encode(text, add_special_tokens=add_special_tokens).ids

  def decode(self, ids, skip_special_tokens=True):
    return self.backend.decode(ids, skip_special_tokens=skip_special_tokens)

  def convert_tokens_to_ids(self, token):
    return self.backend.token_to_id(token)


def normalize(text):
  return re.sub(r'\s+', ' ', text.casefold()).strip()


def token_pieces(token, known):
  """Fewest existing BPE pieces with exactly the same byte-level spelling."""
  best = {len(token): ()}
  for start in range(len(token) - 1, -1, -1):
    choices = [(known[token[start:end]],) + best[end]
               for end in range(start + 1, len(token) + 1)
               if token[start:end] in known and end in best]
    if choices:
      best[start] = min(choices, key=len)
  return best.get(0)


def document(row, kind, excluded):
  if kind == 'python' and (row.get('license', '').casefold() not in PERMISSIVE or row.get('autogenerated')):
    return None, 'license_or_generated'
  text = row.get('text' if kind == 'english' else 'content', '')
  if not isinstance(text, str) or not 200 <= len(text) <= 200_000:
    return None, 'length'
  clean = normalize(text)
  if any(q in clean for q in excluded):
    return None, 'benchmark_literal'
  # These repositories define the private development tasks. The public
  # pretraining stage does not need their source material; verified SFT does.
  if any(s in clean for s in ('fp-risc', 'qosportable', 'qosnative', 'jasonqin/fprisc')):
    return None, 'domain_source'
  group = urlsplit(row.get('url', '')).netloc.casefold() if kind == 'english' else row.get('repo_name', '').casefold()
  if not group:
    return None, 'missing_group'
  content_hash = hashlib.sha256(text.encode()).hexdigest()
  return {'text': text, 'hash': content_hash, 'group': digest([kind, group]),
          'split': 'validation' if int(digest([kind, group])[:8], 16) % 100 == 0 else 'train',
          'license': row.get('license', SOURCES[kind]['license'])}, None


def source_rows(path, kind):
  if kind == 'english':
    import pyarrow.parquet as pq
    for batch in pq.ParquetFile(path).iter_batches(batch_size=256, columns=['text', 'url']):
      yield from batch.to_pylist()
  else:
    with gzip.open(path, 'rt') as handle:
      for line in handle:
        if line.strip():
          yield json.loads(line)


def prepare(args):
  from huggingface_hub import hf_hub_download
  if args.output.exists():
    raise ValueError('Choose a new tokenization directory; never silently reuse partial data')
  args.output.mkdir(parents=True)
  vocabulary = torch.load(args.vocabulary, map_location='cpu', weights_only=True)
  qwen_ids = vocabulary['qwen_ids']; qwen = FrozenTokenizer(args.tokenizer)
  lookup = np.zeros(max(len(qwen), int(qwen_ids.max()) + 1), dtype=np.uint32)
  lookup[qwen_ids[1:].numpy()] = np.arange(1, len(qwen_ids), dtype=np.uint32)
  known_pieces = {qwen.backend.id_to_token(int(qid)): sid for sid, qid in enumerate(qwen_ids) if sid}
  fallback = {}
  excluded = set()
  benchmark_hashes = {}
  for path in args.benchmark:
    benchmark_hashes[str(path)] = file_hash(path)
    excluded.update(normalize(r['question']) for r in read_rows(path) if len(normalize(r['question'])) >= 20)
  results = {}; downloaded = []; seen = set()
  with gzip.open(args.output / 'documents.jsonl.gz', 'wt') as ledger:
    for kind, spec in SOURCES.items():
      limits = {'train': args.english_tokens if kind == 'english' else args.python_tokens,
                'validation': args.validation_tokens}
      counts = {'train': 0, 'validation': 0}; documents = Counter(); rejected = Counter(); licenses = Counter(); unknown = Counter(); expanded = Counter()
      paths = {s: args.output / f'{kind}_{s}.bin' for s in counts}
      handles = {s: paths[s].open('wb', buffering=8 * 1024 * 1024) for s in paths}
      pending = []

      def flush():
        if not pending:
          return
        encoded = qwen.backend.encode_batch([d['text'] for d in pending], add_special_tokens=False)
        for doc, encoded_doc in zip(pending, encoded):
          split = doc['split']
          if counts[split] >= limits[split]:
            continue
          raw = np.asarray(encoded_doc.ids, dtype=np.int64)
          if not len(raw) or int(raw.max()) >= len(lookup):
            rejected['bad_ids'] += 1; continue
          ids = lookup[raw]
          replacements = 0
          if kind == 'python' and (ids == 0).any():
            pieces = []
            for qid, sid in zip(raw.tolist(), ids.tolist()):
              if sid:
                pieces.append(sid)
              else:
                if qid not in fallback:
                  fallback[qid] = token_pieces(qwen.backend.id_to_token(qid), known_pieces)
                replacement = fallback[qid]
                pieces.extend(replacement if replacement is not None else (0,))
                replacements += replacement is not None
            ids = np.asarray(pieces, dtype=np.uint32)
          missing = int((ids == 0).sum())
          if missing / len(ids) > .01:
            rejected['unknown_over_one_percent'] += 1; continue
          if len(ids) < 32:
            rejected['short_encoding'] += 1; continue
          # numpy.tofile flushes Python's buffer on every document. On the
          # network volume those tiny synchronous writes dominate tokenization.
          handles[split].write(ids.tobytes())
          handles[split].write(np.asarray([vocabulary['pad_id']], dtype=np.uint32).tobytes())
          counts[split] += len(ids) + 1; unknown[split] += missing; documents[split] += 1; licenses[doc['license']] += 1
          expanded[split] += replacements
          ledger.write(json.dumps({k: doc[k] for k in ('hash', 'group', 'split', 'license')} | {'source': kind, 'tokens': len(ids) + 1}) + '\n')
        pending.clear()

      try:
        for filename in spec['files']:
          print(json.dumps({'phase': 'download', 'source': kind, 'file': filename}), flush=True)
          path = Path(hf_hub_download(spec['repo'], filename, repo_type='dataset', revision=spec['revision'], token=False))
          downloaded.append({'source': kind, 'filename': filename, 'sha256': file_hash(path), 'bytes': path.stat().st_size})
          for row in source_rows(path, kind):
            doc, reason = document(row, kind, excluded)
            if doc is None:
              rejected[reason] += 1; continue
            if doc['hash'] in seen:
              rejected['duplicate_text'] += 1; continue
            seen.add(doc['hash'])
            if counts[doc['split']] >= limits[doc['split']]:
              continue
            pending.append(doc)
            if len(pending) >= 256:
              flush()
              if sum(documents.values()) % 4096 < 256:
                print(json.dumps({'phase': 'tokenize', 'source': kind, 'tokens': counts}), flush=True)
            if counts['train'] >= limits['train'] and counts['validation'] >= limits['validation']:
              break
          flush()
          if counts['train'] >= limits['train'] and counts['validation'] >= limits['validation']:
            break
      finally:
        for handle in handles.values():
          handle.close()
      if counts['train'] < limits['train'] * .95 or counts['validation'] < min(100_000, limits['validation']):
        raise ValueError('Insufficient distinct data for ' + kind + ': ' + str(counts))
      results[kind] = {'tokens': counts, 'unknown_tokens': dict(unknown), 'documents': dict(documents),
                       'python_qwen_tokens_split_into_existing_pieces': dict(expanded),
                       'licenses': dict(licenses), 'rejected': dict(rejected),
                       'files': {s: {'path': paths[s].name, 'sha256': file_hash(paths[s])} for s in paths}}
  shutil.copyfile(args.vocabulary, args.output / 'vocabulary.pt')
  manifest = {'schema': 1, 'sources': SOURCES, 'results': results, 'downloads': downloaded,
              'vocabulary_sha256': file_hash(args.output / 'vocabulary.pt'),
              'tokenizer_sha256': file_hash(args.tokenizer / 'tokenizer.json'),
              'document_ledger_sha256': file_hash(args.output / 'documents.jsonl.gz'),
              'benchmark_sha256': benchmark_hashes, 'excluded_literal_questions': len(excluded),
              'split_policy': 'whole web-host or code-repository groups hashed 1 percent to validation; exact text dedup globally',
              'exposure_limit': 'literal question and named-domain screening; no semantic decontamination claim',
              'python_encoding': 'Uncovered Qwen BPE tokens are split into existing student pieces with identical byte-level spelling; vocabulary and benchmark encoding unchanged',
              'preparation_code_sha256': file_hash(Path(__file__))}
  manifest['hash'] = digest(manifest)
  write_json(args.output / 'dataset.json', manifest)
  print(json.dumps(manifest, indent=2), flush=True)


def main():
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument('--vocabulary', type=Path, required=True)
  parser.add_argument('--tokenizer', type=Path, required=True)
  parser.add_argument('--benchmark', type=Path, action='append', required=True)
  parser.add_argument('--output', type=Path, required=True)
  parser.add_argument('--english-tokens', type=int, default=400_000_000)
  parser.add_argument('--python-tokens', type=int, default=100_000_000)
  parser.add_argument('--validation-tokens', type=int, default=1_000_000)
  prepare(parser.parse_args())


if __name__ == '__main__':
  main()
