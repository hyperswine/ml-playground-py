import copy
import tempfile
import unittest
from pathlib import Path

import numpy as np
import torch
from torch.nn import functional as F

from qos_ai import QosAi, StudentConfig
from qos_ai_runpod_data import document, token_pieces
from qos_ai_runpod_train import choose_steps, draw, optimizer, pretrain_step, save_progress
from qos_ai_scale import rate


class RunpodTests(unittest.TestCase):
  def test_exact_bpe_fallback_avoids_greedy_dead_ends_and_rejects_missing_bytes(self):
    known = {'ab': 1, 'a': 2, 'bc': 3, '\u0120': 4, 'x': 5}
    self.assertEqual(token_pieces('abc', known), (2, 3))
    self.assertEqual(token_pieces('\u0120x', known), (4, 5))
    self.assertEqual(token_pieces('ab', known), (1,))
    self.assertIsNone(token_pieces('abc?', known))

  def setUp(self):
    torch.set_num_threads(1)

  def test_weighted_accumulation_matches_joint_loss_with_unknown_targets(self):
    torch.manual_seed(7)
    model = QosAi(StudentConfig(16, 8, 16, 2, 2)); control = copy.deepcopy(model)
    streams = {kind: {'train': np.asarray([1, 2, 0, 3, 4, 0, 5, 6] * 30, dtype=np.uint32)} for kind in ('english', 'python')}
    settings = {'seed': 7, 'batch_size': 2, 'sequence_length': 8, 'accumulation': 3,
                'learning_rate': .001, 'total_steps': 4, 'warmup_steps': 1, 'bf16': False}
    a = optimizer(model, .001); b = optimizer(control, .001)
    record = pretrain_step(model, a, streams, settings, 1)
    batches = [draw(streams, 7, 1, m, 2, 8)[0] for m in range(3)]
    combined = torch.cat(batches); count = int((combined[:, 1:] != 0).sum())
    logits = control(combined[:, :-1])
    loss = F.cross_entropy(logits.flatten(0, 1), combined[:, 1:].flatten(), ignore_index=0, reduction='sum') / count
    loss.backward(); torch.nn.utils.clip_grad_norm_(control.parameters(), 1.)
    b.param_groups[0]['lr'] = rate(.001, 1, 4, 1); b.step()
    self.assertEqual(record['known_tokens'], count)
    self.assertEqual(record['tokens'], 48)
    for left, right in zip(model.parameters(), control.parameters()):
      self.assertTrue(torch.allclose(left, right, atol=1e-7, rtol=1e-5))

  def test_public_code_filter_grouping_and_exact_literal_screen(self):
    row = {'content': 'print(1)\n' * 40, 'repo_name': 'Owner/Repo', 'path': 'a.py', 'license': 'mit', 'autogenerated': False}
    first, error = document(row, 'python', set()); self.assertIsNone(error)
    second, _ = document({**row, 'content': 'print(2)\n' * 40, 'path': 'b.py'}, 'python', set())
    self.assertEqual(first['group'], second['group']); self.assertEqual(first['split'], second['split'])
    for changed in ({'license': 'gpl-3.0'}, {'autogenerated': True}):
      self.assertIsNone(document({**row, **changed}, 'python', set())[0])
    self.assertIsNone(document(row, 'python', {'print(1)'})[0])
    self.assertIsNone(document({**row, 'content': row['content'] + ' FP-RISC'}, 'python', set())[0])

  def test_web_host_is_indivisible_validation_group(self):
    a, _ = document({'url': 'https://example.com/a', 'text': 'One educational document. ' * 30}, 'english', set())
    b, _ = document({'url': 'http://EXAMPLE.com/b', 'text': 'Another educational document. ' * 30}, 'english', set())
    self.assertEqual(a['group'], b['group']); self.assertEqual(a['split'], b['split'])

  def test_profile_budget_does_not_exceed_token_or_time_allowance(self):
    for speed, seconds in ((1000, 3600), (15000, 20000), (100000, 20000)):
      steps = choose_steps(speed, seconds, 8192)
      self.assertLessEqual(steps * 8192, 500_000_000)
      self.assertLessEqual(steps * 8192, speed * seconds * .85)
    with self.assertRaises(ValueError):
      choose_steps(1000, 30, 8192)

  def test_atomic_full_checkpoint_keeps_ties_and_adam_moments(self):
    model = QosAi(StudentConfig(16, 8, 16, 2, 1)); opt = optimizer(model, .01)
    model(torch.tensor([[1, 2, 3]])).square().mean().backward(); opt.step(); opt.zero_grad(set_to_none=True)
    with tempfile.TemporaryDirectory() as directory:
      path = Path(directory) / 'progress.pt'
      save_progress(path, model, opt, {'frozen': True}, 1, [{'step': 1}])
      saved = torch.load(path, map_location='cpu', weights_only=True, mmap=True)
      self.assertEqual(saved['step'], 1)
      self.assertTrue(saved['optimizer_state']['state'])
      self.assertEqual(saved['model_state']['token_embedding.weight'].data_ptr(), saved['model_state']['language_model_head.weight'].data_ptr())
      self.assertFalse(path.with_name(path.name + '.partial').exists())


if __name__ == '__main__':
  unittest.main()
